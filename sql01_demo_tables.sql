-- 01_demo_tables.sql
-- Demo master-detail tables for the APEX Master-Detail Generator

CREATE TABLE DEMO_ORDERS (
    ORDER_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY
  , ORDER_NO       VARCHAR2(30)  NOT NULL
  , CUSTOMER_NAME  VARCHAR2(100) NOT NULL
  , ORDER_DATE     DATE          DEFAULT SYSDATE NOT NULL
  , STATUS         VARCHAR2(20)  DEFAULT 'OPEN'
  , CREATED_BY     VARCHAR2(100)
  , CREATED_ON     DATE
  , UPDATED_BY     VARCHAR2(100)
  , UPDATED_ON     DATE
  , CONSTRAINT DEMO_ORDERS_UK UNIQUE (ORDER_NO)
);

CREATE TABLE DEMO_ORDER_ITEMS (
    ITEM_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY
  , ORDER_ID       NUMBER        NOT NULL
  , ITEM_NAME      VARCHAR2(100) NOT NULL
  , QTY            NUMBER        NOT NULL
  , UNIT_PRICE     NUMBER        NOT NULL
  , CREATED_BY     VARCHAR2(100)
  , CREATED_ON     DATE
  , UPDATED_BY     VARCHAR2(100)
  , UPDATED_ON     DATE
  , CONSTRAINT DEMO_ORDER_ITEMS_FK FOREIGN KEY (ORDER_ID) REFERENCES DEMO_ORDERS (ORDER_ID)
);

